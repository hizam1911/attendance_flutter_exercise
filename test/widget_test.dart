import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';

import 'package:flutter_attendance/main.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('Counter increments smoke test', (WidgetTester tester) async {
    // Set up mock SharedPreferences values
    SharedPreferences.setMockInitialValues({}); // Mock any initial values if needed

    // Get the instance of SharedPreferences
    final sharedPreferences = await SharedPreferences.getInstance();

    // Build our app and trigger a frame, passing the sharedPreferences instance
    await tester.pumpWidget(MyApp(sharedPreferences: sharedPreferences));

    // Verify that our counter starts at 0.
    expect(find.text('0'), findsOneWidget);
    expect(find.text('1'), findsNothing);

    // Tap the '+' icon and trigger a frame.
    await tester.tap(find.byIcon(Icons.add));
    await tester.pump();

    // Verify that our counter has incremented.
    expect(find.text('0'), findsNothing);
    expect(find.text('1'), findsOneWidget);
  });
}